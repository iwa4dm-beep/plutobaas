/** Browser-safe random hex (Web Crypto). */
export function randomHex(bytes: number): string {
  const buf = new Uint8Array(bytes);
  globalThis.crypto.getRandomValues(buf);
  return [...buf].map((b) => b.toString(16).padStart(2, "0")).join("");
}

export function withGeneratedSecrets(cfg: LocalStackConfig): LocalStackConfig {
  return {
    ...cfg,
    jwtSecret: cfg.jwtSecret || randomHex(32),
    anonKey: cfg.anonKey || `pluto_anon_${randomHex(16)}`,
    serviceKey: cfg.serviceKey || `pluto_service_${randomHex(24)}`,
  };
}

export type BundleFile = { path: string; contents: string; language: string };

