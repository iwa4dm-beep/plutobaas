// One-click local Docker Compose bundle generator.
//
// Produces a self-contained folder (docker-compose.yml + .env + bootstrap
// script + README) that boots Postgres, MinIO, Mailpit and the Pluto API,
// then runs migrations/import and a first verification pass — all driven
// from the SAME `.env` file so connection, migration and verification never
// drift apart.

export type LocalStackConfig = {
  projectName: string;
  apiPort: number;
  dbPort: number;
  minioPort: number;
  mailpitPort: number;
  dbUser: string;
  dbPassword: string;
  dbName: string;
  jwtSecret: string;
  anonKey: string;
  serviceKey: string;
  frontendOrigin: string;
  /** Optional SQL file (relative to the bundle) applied after migrations. */
  importSqlPath: string;
  withMinio: boolean;
  withMailpit: boolean;
};

